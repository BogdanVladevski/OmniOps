namespace OmniOps.Application.Common.Interfaces;

/// <summary>Records who changed what. Saved with the next <c>SaveChangesAsync</c>.</summary>
public interface IAuditLog
{
    void Record(string action, string entityType, string? entityId, string? details = null);

    /// <summary>For actions taken before sign-in (accepting an invitation, resetting a password).</summary>
    void Record(Guid organizationId, Guid? userId, string action, string entityType, string? entityId, string? details = null);
}

public interface IPasswordHasher
{
    string Hash(string password);

    bool Verify(string password, string hash, out bool needsRehash);
}

/// <summary>Outgoing email. <see cref="IsConfigured"/> is false without a mail server: never claim an email was sent then.</summary>
public interface IEmailSender
{
    bool IsConfigured { get; }

    Task SendAsync(string to, string subject, string body, CancellationToken cancellationToken = default);
}

/// <summary>Photos and signatures. Keys are generated by the application, never by clients.</summary>
public interface IFileStore
{
    Task SaveAsync(string key, Stream content, CancellationToken cancellationToken = default);

    Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken = default);
}

/// <summary>Absolute links for emails and messages.</summary>
public interface IPublicLinks
{
    string Invoice(string token);

    string Tracking(string token);

    /// <summary>The customer's portal: all their deliveries, proof and invoices.</summary>
    string Portal(string token);

    /// <summary>The proof pack (PDF) of one delivered job, opened through the customer's portal link.</summary>
    string PortalProof(string token, Guid jobId);

    /// <summary>Opens the app to accept an invitation to a company.</summary>
    string Join(string token);

    /// <summary>Opens the app to choose a new password.</summary>
    string PasswordReset(string token);
}

/// <summary>Live alerts to the office screens of one company.</summary>
public interface IRealtimeNotifier
{
    Task AlertAsync(Guid organizationId, string kind, string title, string message, Guid? jobId = null, CancellationToken cancellationToken = default);

    /// <summary>
    /// Tells open office screens that a job changed (position, status, paperwork) so they refetch. Best effort: never
    /// throws, and is only called after the change is committed.
    /// </summary>
    Task JobChangedAsync(Guid organizationId, Guid jobId, CancellationToken cancellationToken = default);
}

/// <summary>Ends sign-ins: refresh tokens are revoked and access tokens issued earlier stop working.</summary>
public interface IAccountSessions
{
    /// <summary>Call after the account change is saved.</summary>
    Task RevokeAllAsync(Guid userId, CancellationToken cancellationToken = default);

    /// <summary>False if the account was switched off or its sessions were ended after the token was issued.</summary>
    Task<bool> IsCurrentAsync(Guid userId, DateTime issuedAtUtc, CancellationToken cancellationToken = default);
}

/// <summary>Gap-free invoice numbers per company. Must run inside the transaction that issues the invoice.</summary>
public interface IInvoiceNumbering
{
    Task<int> NextAsync(Guid organizationId, CancellationToken cancellationToken = default);
}

/// <summary>Runs work in one database transaction; a nested call joins the outer one.</summary>
public interface IUnitOfWork
{
    Task<T> InTransactionAsync<T>(Func<CancellationToken, ValueTask<T>> work, CancellationToken cancellationToken = default);
}

/// <summary>Checks the caller against an authorization policy; throws when they are not allowed.</summary>
public interface IPolicyEnforcer
{
    Task EnforceAsync(string policy, CancellationToken cancellationToken = default);
}

/// <summary>Turns a delivery's proof pack into a PDF.</summary>
public interface IProofPackRenderer
{
    byte[] Render(Features.Jobs.ProofPack pack);
}
